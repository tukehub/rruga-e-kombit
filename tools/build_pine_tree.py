#!/usr/bin/env python3
"""Build a mobile pine from Poly Haven's CC0 pine_tree_01.

The original glTF contains three trees and a 949 MB geometry buffer; its first
tree alone has about 6.8 million twig triangles. Importing it then retaining
22% is not mobile safe. We stream the first tree's real trunk and bark, simplify
those in Blender, and reconstruct its crown with spatially distributed cards
using the original pine twig colour/alpha textures. No tree images or other
licensed assets are generated by this script.

Run from the repository root: python3 tools/build_pine_tree.py
The executable needs network access, Blender and Godot 4.4 on PATH.
"""
import json
import shutil
import subprocess
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GODOT = ROOT / 'godot'
ASSET_ID = 'pine_tree_01'
USER_AGENT = 'GodotMobileRacingAssetPipeline/1.0'
OUTPUT = GODOT / 'assets/trees/pine_tree_01_mobile.glb'
SCRIPT = GODOT / 'scripts/pine_forest_multimesh.gd'


def response(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': USER_AGENT}), timeout=60)


def download(url, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    with response(url) as src, path.open('wb') as dst:
        shutil.copyfileobj(src, dst, 1024 * 1024)


def download_tree(folder):
    with response('https://api.polyhaven.com/files/' + ASSET_ID) as src:
        api = json.load(src)
    gltf = api['gltf']['1k']['gltf']
    with response(gltf['url']) as src:
        data = json.load(src)
    # The first two mesh primitives are the first tree's bark and trunk. The
    # following gigantic twig primitive is intentionally excluded before import.
    parts = data['meshes'][0]['primitives'][:2]
    accessors = sorted({p['indices'] for p in parts} |
                       {i for p in parts for i in p['attributes'].values()})
    views = sorted({data['accessors'][i]['bufferView'] for i in accessors})
    need = max(data['bufferViews'][i].get('byteOffset', 0) + data['bufferViews'][i]['byteLength'] for i in views)
    if need > 12 * 1024 * 1024:
        raise ValueError('The source layout changed; inspect its buffers before importing')
    bin_info = gltf['include'][data['buffers'][0]['uri']]
    raw_bin = folder / 'pine_tree_01.bin'
    with response(bin_info['url']) as src, raw_bin.open('wb') as dst:
        left = need
        while left:
            chunk = src.read(min(left, 1024 * 1024))
            if not chunk:
                raise IOError('The source geometry was incomplete')
            dst.write(chunk)
            left -= len(chunk)
    amap = {old: new for new, old in enumerate(accessors)}
    vmap = {old: new for new, old in enumerate(views)}
    for p in parts:
        p['indices'] = amap[p['indices']]
        p['attributes'] = {k: amap[i] for k, i in p['attributes'].items()}
    new_accessors = [data['accessors'][i] for i in accessors]
    for a in new_accessors:
        a['bufferView'] = vmap[a['bufferView']]
    data['accessors'] = new_accessors
    data['bufferViews'] = [data['bufferViews'][i] for i in views]
    data['meshes'] = [dict(data['meshes'][0], primitives=parts)]
    data['nodes'] = [dict(data['nodes'][0], mesh=0, translation=[0, 0, 0])]
    data['scenes'] = [{'nodes': [0]}]
    data['scene'] = 0
    data['materials'] = data['materials'][:2]
    data['textures'] = data['textures'][:6]
    data['images'] = data['images'][:6]
    data['buffers'][0]['byteLength'] = need
    for image in data['images']:
        rel = image['uri']
        download(gltf['include'][rel]['url'], folder / rel)
    twig = folder / 'twig_diff.jpg'
    alpha = folder / 'twig_alpha.png'
    download(gltf['include']['textures/pine_tree_01_twig_diff_1k.jpg']['url'], twig)
    download(api['twig_alpha']['1k']['png']['url'], alpha)
    path = folder / 'pine_tree_01_trunk.gltf'
    path.write_text(json.dumps(data), encoding='utf-8')
    return path, twig, alpha


def write_godot_script():
    SCRIPT.parent.mkdir(parents=True, exist_ok=True)
    SCRIPT.write_text(GDSCRIPT, encoding='utf-8')


GDSCRIPT = '''@tool
extends Node3D
class_name PineForestMultiMesh
## Builds from supplied real tree positions; it never randomly plants on the road.
const TREE_SCENE: PackedScene = preload("res://assets/trees/pine_tree_01_mobile.glb")
const CHUNK_SIZE := 160.0
var planted_transforms: Array[Transform3D] = []

func build_forest(transforms: Array[Transform3D]) -> void:
    for child in get_children():
        remove_child(child)
        child.queue_free()
    planted_transforms = transforms.duplicate()
    if transforms.is_empty():
        return
    var root := TREE_SCENE.instantiate()
    var parts: Array = []
    _collect_meshes(root, Transform3D.IDENTITY, parts)
    var chunks := {}
    for tree in transforms:
        var key := Vector2i(floori(tree.origin.x / CHUNK_SIZE), floori(tree.origin.z / CHUNK_SIZE))
        if not chunks.has(key):
            chunks[key] = []
        chunks[key].append(tree)
    for key: Vector2i in chunks:
        var origin := Vector3((key.x + 0.5) * CHUNK_SIZE, 0, (key.y + 0.5) * CHUNK_SIZE)
        for part in parts:
            var mesh: ArrayMesh = part[0].duplicate(true)
            for surface in mesh.get_surface_count():
                var source := mesh.surface_get_material(surface)
                if source is BaseMaterial3D:
                    var material: BaseMaterial3D = source.duplicate()
                    var material_name := material.resource_name.to_lower()
                    if "needle" in material_name or "foliage" in material_name or material.transparency != BaseMaterial3D.TRANSPARENCY_DISABLED:
                        material.transparency = BaseMaterial3D.TRANSPARENCY_ALPHA_SCISSOR
                        material.alpha_scissor_threshold = 0.5
                        material.cull_mode = BaseMaterial3D.CULL_DISABLED
                    mesh.surface_set_material(surface, material)
            var mm := MultiMesh.new()
            mm.transform_format = MultiMesh.TRANSFORM_3D
            mm.mesh = mesh
            mm.instance_count = chunks[key].size()
            for i in mm.instance_count:
                var t: Transform3D = chunks[key][i] * part[1]
                t.origin -= origin
                mm.set_instance_transform(i, t)
            var node := MultiMeshInstance3D.new()
            node.name = "PineChunk_%d_%d" % [key.x, key.y]
            node.position = origin
            node.multimesh = mm
            node.visibility_range_end = 220.0
            node.visibility_range_end_margin = 25.0
            # Mobile performance: no per-tree dynamic shadow pass.
            node.cast_shadow = GeometryInstance3D.SHADOW_CASTING_SETTING_OFF
            add_child(node)
    root.free()

func _collect_meshes(node: Node, parent_transform: Transform3D, parts: Array) -> void:
    var t := parent_transform
    if node is Node3D:
        t = parent_transform * node.transform
    if node is MeshInstance3D and node.mesh != null:
        parts.append([node.mesh, t])
    for child in node.get_children():
        _collect_meshes(child, t, parts)
'''


def main():
    print('Fetching selected source geometry and materials for', ASSET_ID, flush=True)
    with tempfile.TemporaryDirectory(prefix='vortex-pine-') as tmp:
        source, twig, alpha = download_tree(Path(tmp))
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        print('Simplifying actual pine trunk and building textured foliage', flush=True)
        subprocess.run(['blender', '-b', '-t', '2', '--python', str(ROOT / 'tools/build_pine_tree_model.py'),
                        '--', str(source), str(twig), str(alpha), str(OUTPUT), '0.22'], check=True)
    write_godot_script()
    print('Generated', OUTPUT.relative_to(ROOT), 'and', SCRIPT.relative_to(ROOT), flush=True)


if __name__ == '__main__':
    main()
